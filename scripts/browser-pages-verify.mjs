import { chromium } from 'playwright';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const origin = process.env.TEST_ORIGIN ?? 'http://127.0.0.1:4173/HOUSE/';
const base = new URL(origin).pathname;
const key = `home-studio-project-v1:${encodeURIComponent(base)}`;
const output = 'verification/pages';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
page.setDefaultTimeout(15000);
const report = { startedAt: new Date().toISOString(), checks: [], errors: [], failedRequests: [], imageRequests: [] };
page.on('pageerror', error => report.errors.push(error.message));
page.on('response', response => { if (response.status() >= 400) report.failedRequests.push(response.url()); });
page.on('request', request => { if (new URL(request.url()).pathname.includes('/references/')) report.imageRequests.push(request.url()); });
page.on('dialog', dialog => dialog.accept());
const saved = async () => { await page.waitForTimeout(850); await page.getByText('已存於本機', { exact: true }).waitFor(); return page.evaluate(key => JSON.parse(localStorage.getItem(key)), key); };
try {
  await context.addInitScript(() => localStorage.setItem('home-studio-project-v1:%2FOTHER%2F', 'untouched'));
  const response = await page.goto(origin, { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  let project = await saved();
  assert.equal(project.id, 'home-plan-v1');
  assert.equal(project.rooms.filter(r => r.kind === 'bath').length, 3);
  assert.equal(project.requirements.needs, '');
  assert.equal(project.reference, null);
  await page.getByRole('button', { name: '匯入自己的圖面', exact: true }).click();
  await page.getByText(/網站提供三房三衛示意配置/).waitFor();
  await page.getByRole('button', { name: '關閉對話框', exact: true }).click();
  await page.getByRole('button', { name: '加入書桌', exact: true }).click();
  project = await saved(); assert.equal(project.furniture.length, 9);
  await page.getByRole('button', { name: '復原', exact: true }).click();
  assert.equal((await saved()).furniture.length, 8);
  report.checks.push('子路徑初次載入、無圖匯入入口、家具與復原');
  await page.getByRole('button', { name: '立體空間', exact: true }).click();
  await page.locator('.viewer3d-canvas canvas').waitFor();
  await page.waitForTimeout(700);
  assert.equal(await page.locator('.viewer3d-fallback').count(), 0);
  await page.screenshot({ path: `${output}/3d.png`, fullPage: true });
  await page.getByRole('button', { name: '平面配置', exact: true }).click();
  report.checks.push('子路徑延遲載入 3D');
  const embedded = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 160; canvas.height = 100;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#eee'; ctx.fillRect(0, 0, 160, 100); ctx.strokeRect(20, 20, 120, 60);
    return canvas.toDataURL('image/png');
  });
  const backup = { ...project, reference: { id: 'test-image', name: '測試圖', src: embedded, width: 160, height: 100, x: 0, y: 0, worldWidth: 14, opacity: .4 } };
  await page.getByLabel('選擇方案備份檔案').setInputFiles({ name: 'portable.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await page.getByRole('button', { name: '確認載入', exact: true }).click();
  assert.deepEqual((await saved()).reference, backup.reference);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: '匯出方案', exact: true }).click();
  const download = await downloadEvent; await download.saveAs(`${output}/test-backup.json`);
  assert.deepEqual(JSON.parse(await readFile(`${output}/test-backup.json`, 'utf8')).reference, backup.reference);
  await page.reload({ waitUntil: 'networkidle' });
  assert.deepEqual((await saved()).reference, backup.reference);
  report.checks.push('內嵌圖片備份匯入匯出與重新載入');
  const missing = { ...backup, reference: { ...backup.reference, src: '/references/plan.jpeg' } };
  await page.getByLabel('選擇方案備份檔案').setInputFiles({ name: 'legacy.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(missing)) });
  await page.getByRole('alert').filter({ hasText: '線上版未包含該圖' }).waitFor();
  assert.deepEqual((await saved()).reference, backup.reference);
  await page.getByRole('button', { name: '確認載入', exact: true }).click();
  assert.deepEqual((await saved()).reference, missing.reference);
  await page.getByRole('button', { name: /^圖面校正/ }).click();
  await page.getByRole('alert').filter({ hasText: '線上版未包含該圖' }).waitFor();
  await page.getByRole('button', { name: '匯出方案', exact: true }).click();
  await page.locator('.toast').filter({ hasText: '完整 JSON' }).waitFor();
  assert.deepEqual((await saved()).reference, missing.reference);
  await page.getByLabel('選擇平面圖片').setInputFiles({ name: 'replacement.png', mimeType: 'image/png', buffer: Buffer.from(embedded.split(',')[1], 'base64') });
  assert.ok((await saved()).reference.src.startsWith('data:image/'));
  report.checks.push('缺原圖舊備份提示、原引用保留、禁止假成功匯出及重新選圖');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400); // Wait for the responsive effect to close the desktop panel.
  if (await page.locator('.design-panel.mobile-open').count()) await page.getByRole('button', { name: '收起設定面板' }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true });
  assert.equal(await page.evaluate(() => localStorage.getItem('home-studio-project-v1:%2FOTHER%2F')), 'untouched');
  report.checks.push('手機版面及其他網站儲存隔離');
  assert.deepEqual(report.imageRequests, []);
  assert.deepEqual(report.failedRequests, []);
  assert.deepEqual(report.errors, []);
} catch (error) { report.error = String(error); process.exitCode = 1; }
finally {
  report.completedAt = new Date().toISOString();
  await writeFile(`${output}/results.json`, JSON.stringify(report, null, 2));
  await context.close(); await browser.close();
}
